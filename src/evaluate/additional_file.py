"""Additional file 1 as LaTeX: supplement/additional_file_1.tex, generated (never edited by hand).

Contents, in order: an empty "Supplementary Note S1" section (written by hand in the manuscript), Figures S1-S5 with
their captions, Tables S1-S10. Captions come from the same caption functions as docs/captions.md
(src.evaluate.captions.sections); figures are included from results/figures/ (PDF) and tables are \\input from
results/tables/latex/ (src.evaluate.latex_tables), both by paths relative to supplement/. Figures and tables are
numbered S1, S2, ... by LaTeX. Self-test: five figures, ten tables in label order, every included file present, and
the figure captions pass the reader-label check.

Run from the repo root (after the figures, python -m src.evaluate.latex_tables and the captions):
    python -m src.evaluate.additional_file
Compile (tectonic is not in the project environment; any LaTeX with the packages below works):
    cd supplement && tectonic additional_file_1.tex
The PDF is a build product and is not committed.
"""

import re

from src.config import load_config, repo_path
from src.evaluate import labels as L
from src.evaluate.captions import sections
from src.evaluate.latex_tables import BUILDERS, OUT_DIR, tex_math

OUT = "supplement/additional_file_1.tex"
REL = "../"          # from supplement/ to the repo root

PREAMBLE = r"""% Additional file 1. Generated by python -m src.evaluate.additional_file; do not edit.
% Compile from this folder: tectonic additional_file_1.tex
\documentclass[10pt]{article}
\usepackage[margin=2.5cm]{geometry}
\usepackage{amsmath,amssymb}
\usepackage{booktabs,longtable}
\usepackage{graphicx}
\renewcommand{\thefigure}{S\arabic{figure}}
\renewcommand{\thetable}{S\arabic{table}}
\title{Additional file 1}
\date{}
\begin{document}
\maketitle

\section*{Supplementary Note S1}
% Written by hand in the manuscript.

"""


def figure_tex(output, caption):
    """A full-width figure from results/figures/<name>.pdf with its caption (label 'Figure S<k>.' removed)."""
    name = output.split("/")[-1]
    text = tex_math(re.sub(r"^Figure S\d+\.\s*", "", caption))
    return (f"\\begin{{figure}}[p]\n\\centering\n\\includegraphics[width=\\textwidth]{{{REL}{output}.pdf}}\n"
            f"\\caption{{{text}}}\n\\label{{fig:{name}}}\n\\end{{figure}}\n")


def build(config):
    parts = sections(config)
    figs = [(h, o, t) for h, _, o, t in parts if h.startswith("Figure S")]
    tabs = [h for h, *_ in parts if h.startswith("Table S")]
    if [h for h, *_ in figs] != [f"Figure S{k}" for k in range(1, 6)]:
        raise ValueError(f"expected Figures S1-S5 in order, got {[h for h, *_ in figs]}")
    if tabs != [f"Table S{k}" for k in range(1, 11)]:
        raise ValueError(f"expected Tables S1-S10 in order, got {tabs}")
    body = ["\\section*{Supplementary figures}\n"]
    for heading, output, caption in figs:
        if not repo_path(output + ".pdf").exists():
            raise FileNotFoundError(f"{heading}: {output}.pdf")
        L.check_text(caption, heading)
        body.append(figure_tex(output, caption))
    body.append("\\clearpage\n\\section*{Supplementary tables}\n")
    for heading in tabs:
        name = BUILDERS[heading][0]
        if not repo_path(f"{OUT_DIR}/{name}").exists():
            raise FileNotFoundError(f"{heading}: {OUT_DIR}/{name}")
        body.append(f"\\input{{{REL}{OUT_DIR}/{name}}}\n\\clearpage\n")
    return PREAMBLE + "\n".join(body) + "\n\\end{document}\n"


def main():
    config = load_config()
    path = repo_path(OUT)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build(config), encoding="utf-8")
    print(f"Saved {path} (Figures S1-S5, Tables S1-S10)")


if __name__ == "__main__":
    main()
