"""Task 5F: write every figure and table caption to docs/captions.md.

The captions come from the caption functions of the scripts that make each figure and table (which fill
in their numbers from results/), so docs/captions.md cannot drift from the figures, the tables or the
scripts' own printout. Do not edit docs/captions.md by hand; rerun this script.

Run from the repo root (after the figures and tables):
    python -m src.evaluate.captions
"""

from src.config import load_config, repo_path
from src.evaluate import tables
from src.evaluate.figures import fig2_inputs, fig3_b_minus_a, fig4_breakeven, fig5_methods

HEADER = (
    "# Figure and table captions\n\n"
    "Generated by `python -m src.evaluate.captions` from the caption functions in the figure and table "
    "scripts, with numbers computed from `results/`. Do not edit by hand.\n\n"
    "Figure 1 (pipeline schematic) is drawn by hand and has no generated caption.\n"
)


def sections(config):
    """[(heading, source, output, caption)] in manuscript order."""
    fig5 = fig5_methods.captions(config)
    tab = tables.captions(config)
    out = [
        ("Figure 2", "src/evaluate/figures/fig2_inputs.py", "results/figures/fig2_inputs", fig2_inputs.caption(config)),
        ("Figure 3", "src/evaluate/figures/fig3_b_minus_a.py", "results/figures/fig3_b_minus_a",
         fig3_b_minus_a.caption(config)),
        ("Figure 4", "src/evaluate/figures/fig4_breakeven.py", "results/figures/fig4_breakeven",
         fig4_breakeven.caption(config)),
        ("Figure 5", "src/evaluate/figures/fig5_methods.py", "results/figures/fig5_methods", fig5["fig5_methods"]),
    ]
    out += [(f"Figure S{k}", "src/evaluate/figures/fig5_methods.py", f"results/figures/{name}", text)
            for k, (name, text) in enumerate(((n, t) for n, t in fig5.items() if n != "fig5_methods"), start=1)]
    headings = {"table1_detection_limits.csv": "Table 1", "table2_realism_yang.csv": "Table 2",
                "tableS_bopt_cutoff.csv": "Table S1", "tableS_c2_importances.csv": "Table S2",
                "tableS_w_vs_wfixed.csv": "Table S3", "tableS_w_vs_wfixed_limits.csv": "Table S4"}
    out += [(headings[name], "src/evaluate/tables.py", f"results/tables/{name}", text) for name, text in tab.items()]
    return out


def main():
    config = load_config()
    parts = [HEADER]
    for heading, source, output, text in sections(config):
        parts.append(f"\n## {heading}\n\nOutput: `{output}` · script: `{source}`\n\n{text}\n")
    path = repo_path("docs/captions.md")
    path.write_text("".join(parts), encoding="utf-8")
    print(f"Saved {path} ({len(parts) - 1} captions)")


if __name__ == "__main__":
    main()
