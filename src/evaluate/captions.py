"""Task 5F: write every figure and table caption to docs/captions.md.

Numbering follows the manuscript (Task 10): Figs. 2-5, Figs. S1-S5, Table 1 (Yang), Table 2 (detection limits),
Tables S1-S10 (S9 has parts a-d and S10 parts a-c, within one table each). The captions come from the caption
functions of the scripts that make each figure and table, so docs/captions.md cannot drift from the figures, the
tables or the scripts' own printout. Captions describe what is shown: no internal references (decision numbers,
task numbers) and no result statements; the numbers quoted in the text are in docs/revision_numbers.md. Formulas
are written as $...$ math and methods, scenarios and bases by their reader labels (W (FF 10%), +10 bp, matched
FPR, ...), as in the LaTeX tables. check() enforces the internal-reference, label and underscore rules. Do not edit docs/captions.md by hand; rerun this script.

Run from the repo root (after the figures and tables):
    python -m src.evaluate.captions
"""

import re

from src.config import load_config, repo_path
from src.evaluate import tables
from src.evaluate.labels import check_text, outside_math
from src.evaluate.figures import (fig2_inputs, fig3_b_minus_a, fig4_breakeven, fig5_methods, figS_profiles,
                                  figS_short_noise, figS_unified_model)

HEADER = (
    "# Figure and table captions\n\n"
    "Generated by `python -m src.evaluate.captions` from the caption functions in the figure and table "
    "scripts. Captions describe what is shown; the numbers quoted in the text are in `docs/revision_numbers.md`. "
    "Do not edit by hand.\n\n"
    "Figure 1 (pipeline schematic) is drawn by hand and has no generated caption.\n"
)


def sections(config):
    """[(heading, source, output, caption)] in manuscript order."""
    fig5 = fig5_methods.captions(config)
    tab = tables.captions(config)
    out = [
        ("Figure 2", "src/evaluate/figures/fig2_inputs.py", "results/figures/fig2_inputs", fig2_inputs.caption(config)),
        ("Figure 3", "src/evaluate/figures/fig3_b_minus_a.py", "results/figures/fig3_b_minus_a",
         fig3_b_minus_a.caption(config)),
        ("Figure 4", "src/evaluate/figures/fig4_breakeven.py", "results/figures/fig4_breakeven",
         fig4_breakeven.caption(config)),
        ("Figure 5", "src/evaluate/figures/fig5_methods.py", "results/figures/fig5_methods", fig5["fig5_methods"]),
    ]
    out += [(f"Figure S{k}", "src/evaluate/figures/fig5_methods.py", f"results/figures/{name}", text)
            for k, (name, text) in enumerate(((n, t) for n, t in fig5.items() if n != "fig5_methods"), start=1)]
    out.append(("Figure S3", "src/evaluate/figures/figS_unified_model.py",
                "results/figures/figS3_unified_model", figS_unified_model.caption(config)))
    out.append(("Figure S4", "src/evaluate/figures/figS_profiles.py",
                "results/figures/figS4_profiles", figS_profiles.caption(config)))
    out.append(("Figure S5", "src/evaluate/figures/figS_short_noise.py",
                "results/figures/figS5_short_noise", figS_short_noise.caption(config)))
    out += [(label, "src/evaluate/tables.py", ", ".join(f"results/tables/{f}" for f in files), text)
            for label, (files, text) in tab.items()]
    return out


INTERNAL = re.compile(r"decision\s*#|#\s*\d|\bTask\s*\d|\bdecisions?\.md")
PARTS = {"Table S9": "a–d", "Table S10": "a–c"}


def check(heading, text):
    """Self-test: a caption starts with its own label and has no internal reference (decision #, Task NN), no old
    label (labels.OLD_LABELS), no underscore outside $...$ math except in a file name (*.csv) and no hard-coded
    reference number like [7] (citations are added in main.tex)."""
    if not text.startswith(heading + "."):
        raise ValueError(f"{heading}: caption does not start with its label")
    if INTERNAL.search(text):
        raise ValueError(f"{heading}: internal reference {INTERNAL.search(text).group(0)!r} in the caption")
    check_text(re.sub(r"\S+\.csv\b", "", text), heading)
    if re.search(r"\[\d+(?:[,–-]\s*\d+)*\]", outside_math(text)):
        raise ValueError(f"{heading}: hard-coded reference number")


def main():
    config = load_config()
    parts = [HEADER]
    for heading, source, output, text in sections(config):
        check(heading, text)
        if heading in PARTS:
            heading = f"{heading} (parts {PARTS[heading]}, one table)"
        parts.append(f"\n## {heading}\n\nOutput: `{output}` · script: `{source}`\n\n{text}\n")
    path = repo_path("docs/captions.md")
    path.write_text("".join(parts), encoding="utf-8")
    print(f"Saved {path} ({len(parts) - 1} captions)")


if __name__ == "__main__":
    main()
